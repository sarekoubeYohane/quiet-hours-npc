import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { launchBrowser } from './browser-runtime.mjs';
const { startApp } = await import(process.env.REAL_ROUTE_RUNTIME ? pathToFileURL(process.env.REAL_ROUTE_RUNTIME).href : './real-route-runtime.mjs');
const app = await startApp({ modelResponder: request => {
  const input = JSON.parse(request.messages.at(-1).content);
  assert.equal(input.filled.name, '孟澄'); assert.equal(input.filled.personality,'安靜');
  return {name:'擅自改名',personality:'擅自改性格',appearance:'綠色外套',abilities:'修鐘',background:'在河畔學修鐘。',initialMemories:'記得外公的工作桌',beliefs:'答應的事要做到',preferences:'沒有特殊設定',directions:'修好老鐘'};
} });
const browser = await launchBrowser();
const artifacts = process.env.BROWSER_ARTIFACT_DIR || '/tmp/character-drafts-284';
await mkdir(artifacts,{recursive:true});
const context = await browser.newContext();
await context.addCookies([{name:'qh_local_owner',value:'t3-account-a',url:app.url}]);
const page = await context.newPage();
const evidence=[];
try {
  await page.goto(app.url);
  await page.getByRole('link',{name:'人物範本',exact:true}).click();
  assert.equal(new URL(page.url()).pathname,'/character-templates');
  await page.getByRole('button',{name:'新建建角草稿',exact:true}).click();
  await page.locator('[name="draftConcept"]').fill('安靜的河畔修鐘人');
  await page.locator('[name="draft-name"]').fill('孟澄');
  await page.locator('[name="draft-personality"]').fill('安靜');
  await page.getByText('已保存至帳號',{exact:true}).waitFor();
  evidence.push({phase:'manual draft',url:page.url(),title:await page.title()});
  const configured=await page.evaluate(async()=>{
    const post=async data=>{const r=await fetch('/api/world?workspace=account',{method:'POST',headers:{'Content-Type':'application/json','X-World-Time-Policy':'round-v1'},body:JSON.stringify({operationId:Date.now()+':'+crypto.randomUUID(),mode:'demo',...data})});return {status:r.status,body:await r.json()};};
    const key=await post({operation:'set-model-key',mode:'openai',key:'controlled-local-key'});
    const settings=await post({operation:'set-adjudication',adjudication:{provider:'openai',model:'gpt-6.1-sol'}});
    return {key:key.status,settings:settings.status};
  });
  assert.deepEqual(configured,{key:200,settings:200});
  await page.getByRole('button',{name:'用 AI 補完空白文字',exact:true}).click();
  await page.getByText('已補完空白並保存至帳號',{exact:true}).waitFor();
  assert.equal(await page.locator('[name="draft-name"]').inputValue(),'孟澄');
  assert.equal(await page.locator('[name="draft-personality"]').inputValue(),'安靜');
  assert.equal(await page.locator('[name="draft-background"]').inputValue(),'在河畔學修鐘。');
  await page.locator('[name="draft-background"]').fill('在河畔，學修鐘！');
  await page.getByText('已保存至帳號',{exact:true}).waitFor();
  const saved=await page.evaluate(async()=>{const r=await fetch('/api/character-drafts');return r.json();});
  assert.equal(saved.drafts.length,1);assert.equal(saved.drafts[0].provenance.background.kind,'ai');
  assert.equal(saved.drafts[0].provenance.background.materiallyEdited,false);
  await page.screenshot({path:artifacts+'/same-page.png',fullPage:true});
  await page.reload();
  await page.getByRole('button',{name:'孟澄',exact:true}).click();
  assert.equal(await page.locator('[name="draft-background"]').inputValue(),'在河畔，學修鐘！');
  const other=await browser.newContext();await other.addCookies([{name:'qh_local_owner',value:'t3-account-a',url:app.url}]);
  const device=await other.newPage();await device.goto(app.url+'/character-templates');await device.getByRole('button',{name:'孟澄',exact:true}).click();
  assert.equal(await device.locator('[name="draft-background"]').inputValue(),'在河畔，學修鐘！');
  await device.locator('[name="draft-beliefs"]').fill('另一裝置的新信念');await device.getByText('已保存至帳號',{exact:true}).waitFor();
  await page.locator('[name="draft-directions"]').fill('本頁尚未同步的方向');
  await page.getByText(/未同步：另一頁已修改草稿/).waitFor();
  assert.equal(await page.locator('[name="draft-directions"]').inputValue(),'本頁尚未同步的方向');
  await page.screenshot({path:artifacts+'/conflict.png',fullPage:true});
  evidence.push({phase:'reload/second device/conflict',url:page.url(),modelCalls:app.modelRequests.length});
  await other.close();
  assert.equal(app.modelRequests.length,1);
  const privateContext=await browser.newContext();await privateContext.addCookies([{name:'qh_local_owner',value:'t3-account-b',url:app.url}]);const otherPage=await privateContext.newPage();await otherPage.goto(app.url+'/character-templates');
  assert.equal(await otherPage.getByRole('button',{name:'孟澄',exact:true}).count(),0);
  await privateContext.close();
  await writeFile(artifacts+'/evidence.json',JSON.stringify({origin:app.url,commit:app.commit,builtAt:app.builtAt,auth:'local cookie identity boundary; not production OAuth',sqlite:app.sqlitePath,evidence,modelCalls:app.modelRequests.length,paidCalls:0},null,2));
  console.log(JSON.stringify({ok:true,artifacts,evidence}));
} catch(error) {await page.screenshot({path:artifacts+'/failure.png',fullPage:true});await writeFile(artifacts+'/failure.txt',String(error)+'\n'+await page.locator('body').innerText());throw error;} finally {await context.close();await browser.close();await app.close();}
